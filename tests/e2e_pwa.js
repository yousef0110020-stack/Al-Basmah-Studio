// PWA + login + HTTPS test in iPhone emulation. Usage: node tests/e2e_pwa.js https://host password [outDir]
const { chromium, devices } = require("playwright");
const path = require("path"), fs = require("fs");
const [BASE, PW] = [process.argv[2], process.argv[3]];
const OUT = process.argv[4] || path.join(__dirname, "..", "test-results");
const S = path.join(__dirname, "..", "samples");
const res = []; const ok = (n, p, i = "") => { res.push({ n, p, i }); console.log(p ? "PASS" : "FAIL", n, i); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices["iPhone 13"], ignoreHTTPSErrors: true });
  const page = await ctx.newPage();
  await page.goto(BASE + "/");
  ok("redirected to login when signed out", page.url().endsWith("/login.html"));
  await page.screenshot({ path: `${OUT}/pwa_01_login.png` });
  await page.fill("#pw", "wrong-password");
  await page.click("button[type=submit]");
  await page.waitForFunction(() => document.querySelector("#msg").textContent.length > 0);
  ok("wrong password rejected", page.url().endsWith("/login.html"));
  await page.fill("#pw", PW);
  await page.click("button[type=submit]");
  await page.waitForSelector("#photoStyles .chip");
  ok("login works", true);
  const man = await page.evaluate(async () => (await fetch(document.querySelector('link[rel=manifest]').href)).json());
  ok("manifest standalone + icons", man.display === "standalone" && man.icons.length >= 3);
  const touch = await page.evaluate(async () => (await fetch(document.querySelector('link[rel=apple-touch-icon]').href)).status);
  ok("apple-touch-icon served", touch === 200);
  await page.waitForFunction(() => navigator.serviceWorker && navigator.serviceWorker.controller !== undefined, null, { timeout: 5000 }).catch(() => {});
  const sw = await page.evaluate(async () => !!(await navigator.serviceWorker.getRegistration()));
  ok("service worker registered", sw, BASE.includes("localhost") && BASE.startsWith("https") ? "(browsers refuse SW on a self-signed test cert; checked separately)" : "");
  await page.setInputFiles("#photoInput", [path.join(S, "facade_tilted_12mp.jpg")]);
  await page.waitForFunction(() => /عقاري|ليلي/.test(document.querySelector("#photoAnalysis").textContent), null, { timeout: 60000 });
  await page.click("#pExport");
  await page.waitForSelector("#photoJob a[download]", { timeout: 120000 });
  const href = await page.$eval("#photoJob a[download]", a => a.href);
  const dl = await page.evaluate(async h => { const r = await fetch(h); return [r.status, (await r.blob()).size]; }, href);
  ok("photo processed + downloadable over HTTPS", dl[0] === 200 && dl[1] > 10000, `${dl[1]} bytes`);
  await page.screenshot({ path: `${OUT}/pwa_02_home.png` });
  await page.click("#logoutBtn");
  await page.waitForURL(/login/);
  const after = await page.evaluate(async () => (await fetch("/api/files")).status);
  ok("logout ends session", after === 401);
  fs.writeFileSync(`${OUT}/pwa_results.json`, JSON.stringify(res, null, 2));
  await b.close();
  const f = res.filter(r => !r.p).length; console.log(`${res.length - f}/${res.length} passed`); process.exit(f ? 1 : 0);
})().catch(e => { console.error(e); process.exit(2); });
